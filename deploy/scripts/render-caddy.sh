#!/usr/bin/env bash
# Writes deploy/orgs/caddy/sites.caddy: one Caddy site entry per organisation in
# deploy/orgs/orgs.list. The file is replaced atomically. Run by create-org.sh,
# remove-org.sh and edge.sh; safe to run by hand (then: edge.sh reload).
#   deploy/scripts/render-caddy.sh
set -euo pipefail
SIMGUARD_LIB_DEFER=1 source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

out_dir="$ORGS_DIR/caddy"
mkdir -p "$out_dir"
tmp="$(mktemp "$out_dir/.sites.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by deploy/scripts/render-caddy.sh from deploy/orgs/orgs.list. Do not edit."
  while read -r slug project _envfile host; do
    [[ -n "$slug" ]] || continue
    [[ "$host" =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]] || { echo "Bad host '$host' for $slug in $ORGS_LIST" >&2; exit 2; }
    [[ "$project" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || { echo "Bad project '$project' for $slug in $ORGS_LIST" >&2; exit 2; }
    cat <<SITE

# organisation: $slug
$host {
	import simguard_site
	reverse_proxy $project-web:3000 {
		# The web app forwards this to the API for the per-IP rate limit. Caddy
		# overwrites any value a visitor sends.
		header_up X-Forwarded-For {remote_host}
	}
}
SITE
  done < <(org_lines)
} > "$tmp"
chmod 644 "$tmp"
mv -f "$tmp" "$out_dir/sites.caddy"
trap - EXIT
echo "Wrote $(org_lines | wc -l | tr -d ' ') site entr(ies) to $out_dir/sites.caddy"
